// Split original compact catalogs into lazy chapter modules, without changing
// any tuples. Keep original catalogs for provenance and independent audits.
const fs = require('node:fs');
const path = require('node:path');
const readers = require('../data/quranReciters').QURAN_RECITERS.map(r => r.id);
const check = process.argv.includes('--check');
const catalog = ['// Generated by scripts/prepare-quran-chapter-timings.cjs.', 'const readers = {'];
function output(file, value) {
  if (check) { if (fs.readFileSync(file,'utf8') !== value) throw Error(`Stale generated file: ${file}`); }
  else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file,value); }
}
for (const reader of readers) {
  const data = JSON.parse(fs.readFileSync(`data/quran/audio/${reader}.json`, 'utf8'));
  catalog.push(`  ${reader}: [null,`);
  for (let chapter=1;chapter<=114;chapter++) {
    output(`data/quran/audio/${reader}/${chapter}.json`, JSON.stringify(Object.fromEntries(Object.entries(data).filter(([key])=>key.startsWith(`${chapter}:`))))+'\n');
    catalog.push(`    () => require('../data/quran/audio/${reader}/${chapter}.json'),`);
  }
  catalog.push('  ],');
}
catalog.push('};', 'function chapterTimings(reader, chapter) { return readers[reader]?.[chapter]?.() || {}; }', 'module.exports = { chapterTimings };', '');
output('utils/quranTimingCatalog.js', catalog.join('\n'));
console.log('798 chapter catalogs match their source tuples.');
